// Writes what search engines need to find each treatment page, from the one
// catalogue (data/catalog.js):
//
//   public/sitemap.xml      the general pages plus every treatment and package
//   functions/_services.js  slug -> name/description per side, and the legacy
//                           slugs, for functions/service.js and gent-service.js
//
// Run after changing catalog.js (a name, a description, a new treatment, or
// ECO.site for the launch domain):  node tools/seo.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const w = {};
new Function('window', readFileSync('data/catalog.js', 'utf8'))(w);
const E = w.ECO;
const SITE = E.site.replace(/\/$/, '');

const PAGES = ['/', '/for-her', '/for-him', '/about', '/gent-about', '/services', '/gent-services',
  '/gallery', '/gent-gallery', '/book', '/gent-book'];
const DETAIL = { her: '/service', him: '/gent-service' };

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const urls = PAGES.map(p => SITE + p);
const data = { site: SITE, sides: {} };
for (const side of ['her', 'him']) {
  const services = {};
  for (const s of E.flat(side)) {
    urls.push(SITE + DETAIL[side] + '?s=' + s.slug);
    services[s.slug] = { name: s.name, desc: s.desc, cat: s.cat };
  }
  data.sides[side] = { path: DETAIL[side], services, legacy: E.legacy[side] || {} };
}

writeFileSync('public/sitemap.xml',
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map(u => '  <url><loc>' + esc(u) + '</loc></url>').join('\n') + '\n</urlset>\n');

writeFileSync('functions/_services.js',
  '// Generated by tools/seo.mjs from data/catalog.js - do not edit by hand.\n' +
  'export default ' + JSON.stringify(data, null, 1) + ';\n');

writeFileSync('public/robots.txt', 'User-agent: *\nAllow: /\nSitemap: ' + SITE + '/sitemap.xml\n');

console.log('sitemap:', urls.length, 'URLs;', Object.keys(data.sides.her.services).length, 'her +',
  Object.keys(data.sides.him.services).length, 'him treatments');
